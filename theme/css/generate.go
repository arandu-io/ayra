package css

import (
	"bytes"
	"fmt"
	"go/format"
	"image/color"
	"reflect"
	"sort"

	"github.com/arandu-io/ayra/theme"
)

// Generate writes the theme of the stylesheet as Go source: a function that
// answers the theme for a scheme, with only the values that differ from the
// default theme written out.
//
// The output is for a product that would rather commit the result than read a
// file when it starts, which is the choice the default palette made too. Like
// that one it is meant to be checked: regenerate in a test and compare, so that
// a stylesheet edited without regenerating, and a generated file edited by
// hand, both fail.
//
//	//go:generate go run github.com/arandu-io/ayra/theme/css/cmd/themegen -package brand -o theme_gen.go custom.css
func Generate(s *Sheet, pkg, from string, options ...Options) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by theme/css from %s. DO NOT EDIT.\n\n", from)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n\t\"image/color\"\n\n\t\"github.com/arandu-io/ayra/theme\"\n)\n\n")
	b.WriteString("// Theme answers the theme of the product's stylesheet for a scheme: the default\n")
	b.WriteString("// theme with the stylesheet's tokens laid over it.\n")
	b.WriteString("func Theme(scheme theme.Scheme) theme.Theme {\n")
	b.WriteString("\tt := theme.New(scheme)\n\n")
	b.WriteString("\tif scheme == theme.Dark {\n")
	emit(&b, s, theme.Dark, "\t\t", options)
	b.WriteString("\t\treturn t\n\t}\n\n")
	emit(&b, s, theme.Light, "\t", options)
	b.WriteString("\treturn t\n}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("ayra/theme/css: formatting the generated source: %w", err)
	}
	return out, nil
}

// emit writes the assignments that turn the default theme of a scheme into the
// stylesheet's.
func emit(b *bytes.Buffer, s *Sheet, scheme theme.Scheme, indent string, options []Options) {
	base, made := theme.New(scheme), s.Theme(scheme, options...)

	basePalette, madePalette := reflect.ValueOf(base.Colours), reflect.ValueOf(made.Colours)
	for i := 0; i < madePalette.NumField(); i++ {
		if madePalette.Field(i).Interface() != basePalette.Field(i).Interface() {
			c := madePalette.Field(i).Interface().(color.NRGBA)
			fmt.Fprintf(b, "%st.Colours.%s = %s\n", indent, madePalette.Type().Field(i).Name, literal(c))
		}
	}

	baseMetrics, madeMetrics := reflect.ValueOf(base.Metrics), reflect.ValueOf(made.Metrics)
	for i := 0; i < madeMetrics.NumField(); i++ {
		if madeMetrics.Field(i).Float() != baseMetrics.Field(i).Float() {
			fmt.Fprintf(b, "%st.Metrics.%s = %g\n", indent, madeMetrics.Type().Field(i).Name, madeMetrics.Field(i).Float())
		}
	}

	if made.Type.Sans != base.Type.Sans {
		fmt.Fprintf(b, "%st.Type.Sans = %q\n", indent, made.Type.Sans)
	}
	if made.Type.Monospace != base.Type.Monospace {
		fmt.Fprintf(b, "%st.Type.Monospace = %q\n", indent, made.Type.Monospace)
	}

	if made.Styles != nil && len(made.Styles.Tokens) > 0 {
		tokens := made.Styles.Tokens
		names := make([]string, 0, len(tokens))
		for name := range tokens {
			names = append(names, name)
		}
		sort.Strings(names)
		fmt.Fprintf(b, "%st.Styles = &theme.Styles{Tokens: map[string]color.NRGBA{\n", indent)
		for _, name := range names {
			fmt.Fprintf(b, "%s\t%q: %s,\n", indent, name, literal(tokens[name]))
		}
		fmt.Fprintf(b, "%s}}\n", indent)
	}
}

func literal(c color.NRGBA) string {
	return fmt.Sprintf("color.NRGBA{R: %d, G: %d, B: %d, A: %d}", c.R, c.G, c.B, c.A)
}
