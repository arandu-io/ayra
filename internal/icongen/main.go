// Command icongen writes Ayra's icons from the ones Kyse already has.
//
// The set is the same on both halves -- the same Phosphor icons, under the same
// function names -- and the way to keep it the same is to have one source. Kyse
// generates its functions from Phosphor's own repository; this reads what Kyse
// generated, takes the path data and the doc comment of each function, and
// writes them again as data an Ayra widget can draw. A name added to Kyse
// arrives here at the next run, and a test compares the two in both directions
// whenever Kyse is beside this repository.
//
// Usage:
//
//	icongen <kyse/icons directory> <ayra/icons directory> <ayra/icons/lookup directory>
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type icon struct {
	name, doc, shade, body, kebab string
}

var kebab = regexp.MustCompile(`Phosphor "([^"]+)" icon`)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: icongen <kyse/icons> <ayra/icons> <ayra/icons/lookup>")
		os.Exit(2)
	}
	icons, err := read(os.Args[1])
	if err != nil {
		fail(err)
	}

	byLetter := map[string][]icon{}
	for _, i := range icons {
		letter := strings.ToLower(i.name[:1])
		byLetter[letter] = append(byLetter[letter], i)
	}

	for letter, group := range byLetter {
		var b bytes.Buffer
		b.WriteString("// Code generated by internal/icongen from kyse/icons. DO NOT EDIT.\n//\n")
		b.WriteString("// Phosphor Icons 2.1.1, duotone weight, from\n// https://github.com/phosphor-icons/core\n//\n")
		b.WriteString("// The paths are MIT, Copyright (c) 2023 Phosphor Icons. The licence is in\n// LICENSE.md beside this file.\n\npackage icons\n\n")
		for _, i := range group {
			fmt.Fprintf(&b, "%s\nfunc %s() Icon { return Icon{shade: %s, body: %s} }\n\n", i.doc, i.name, strconv.Quote(i.shade), strconv.Quote(i.body))
		}
		write(filepath.Join(os.Args[2], "icons_"+letter+".go"), b.Bytes())
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/icongen from kyse/icons. DO NOT EDIT.\n\npackage lookup\n\n")
	b.WriteString("import \"github.com/arandu-io/ayra/icons\"\n\n")
	b.WriteString("// all is every icon, by the name of its Go function and by Phosphor's own name.\n")
	b.WriteString("var all = map[string]func() icons.Icon{\n")
	for _, i := range icons {
		fmt.Fprintf(&b, "\t%q: icons.%s,\n", i.name, i.name)
		if i.kebab != "" {
			fmt.Fprintf(&b, "\t%q: icons.%s,\n", i.kebab, i.name)
		}
	}
	b.WriteString("}\n")
	write(filepath.Join(os.Args[3], "lookup_gen.go"), b.Bytes())
}

// read answers every icon of a directory of Kyse's, sorted by name.
func read(dir string) ([]icon, error) {
	files, err := filepath.Glob(filepath.Join(dir, "icons_*.go"))
	if err != nil || len(files) == 0 {
		return nil, fmt.Errorf("no icons_*.go in %s", dir)
	}
	sort.Strings(files)

	var found []icon
	for _, path := range files {
		parsed, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range parsed.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || fn.Body == nil || len(fn.Body.List) != 1 {
				continue
			}
			ret, ok := fn.Body.List[0].(*ast.ReturnStmt)
			if !ok || len(ret.Results) != 1 {
				continue
			}
			call, ok := ret.Results[0].(*ast.CallExpr)
			if !ok || len(call.Args) != 3 {
				continue
			}
			shade, ok1 := unquote(call.Args[1])
			body, ok2 := unquote(call.Args[2])
			if !ok1 || !ok2 {
				return nil, fmt.Errorf("%s: %s has path data that is not a literal", path, fn.Name.Name)
			}

			doc := ""
			if fn.Doc != nil {
				for _, c := range fn.Doc.List {
					doc += c.Text + "\n"
				}
				doc = strings.TrimRight(doc, "\n")
			}
			i := icon{name: fn.Name.Name, doc: doc, shade: shade, body: body}
			if m := kebab.FindStringSubmatch(strings.ReplaceAll(doc, "\n// ", " ")); m != nil {
				i.kebab = m[1]
			}
			found = append(found, i)
		}
	}
	sort.Slice(found, func(a, b int) bool { return found[a].name < found[b].name })
	return found, nil
}

func unquote(e ast.Expr) (string, bool) {
	lit, ok := e.(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return "", false
	}
	s, err := strconv.Unquote(lit.Value)
	return s, err == nil
}

func write(path string, source []byte) {
	out, err := format.Source(source)
	if err != nil {
		fail(fmt.Errorf("%s: %w", path, err))
	}
	if err := os.WriteFile(path, out, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "icongen:", err)
	os.Exit(1)
}
